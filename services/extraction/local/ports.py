"""Application ports; domain and orchestration do not import database drivers."""
from contextlib import AbstractContextManager
from typing import Any, Protocol
from services.extraction.local.session import LocalSession


class LocalFlyerRepository(Protocol):
    def locked(self, flyer_id: str) -> AbstractContextManager[tuple[Any, dict]]: ...
    def save(self, cursor: Any, flyer: dict, session: LocalSession,
             status: str = 'processing', error: str | None = None) -> None: ...
    def insert_offers(self, cursor: Any, rows: list[dict]) -> None: ...
    def draft_count(self, cursor: Any, flyer_id: str) -> int: ...
    def reject_published(self, cursor: Any, flyer_id: str) -> None: ...
